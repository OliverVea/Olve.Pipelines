// olve-build: pipeline dir → single executable + step.tar.zst + manifest.json.
import { existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { canonicalJson } from "../util/canonical.ts";
import { sha256File } from "../util/hash.ts";
import type { HarnessInfo } from "../util/handler-hash.ts";
import { writeTarZst } from "../util/tar.ts";
import { MANIFEST_BEGIN, MANIFEST_END, uploadFile } from "../harness/result.ts";
import { GLIBC_INTERP, MUSL_INTERP, readInterpreter } from "./elf.ts";
import { handlerHashes, type HandlerHash } from "./hashes.ts";
import { harnessInfo, loadProject, relPosix, type Project } from "./project.ts";

export const BUILD_FLAGS = ["--no-compile-autoload-dotenv", "--no-compile-autoload-bunfig", "--bytecode", "--format=esm"] as const;
export type Target = "bun-linux-x64" | "bun-linux-x64-musl";

export class BuildError extends Error {
  override name = "BuildError";
  constructor(message: string, readonly exitCode = 1) {
    super(message);
  }
}

export interface BuildOptions {
  out: string;
  target?: Target;
  /** Pre-signed PUT for the step archive. */
  uploadUrl?: string;
  /** Print the manifest between sentinels on stdout (for the build Job's pod log). */
  sentinels?: boolean;
  log?: (line: string) => void;
  stdout?: (text: string) => Promise<void>;
}

export interface BuildResult {
  binary: string;
  archive: string;
  manifestFile: string;
  manifest: string;
  hashes: Record<string, HandlerHash>;
  harness: HarnessInfo;
}

/** Writes `<dir>/.olve/gen/{handlers,entry}.ts`: the literal-import handler registry + binary entry. */
export function generateEntry(project: Project, hashes: Record<string, string>, harness: HarnessInfo): string {
  const gen = join(project.dir, ".olve", "gen");
  mkdirSync(gen, { recursive: true });
  const registry = project.handlers.map(([name, file]) => `  ${JSON.stringify(name)}: () => import(${JSON.stringify(relPosix(gen, file))}),`).join("\n");
  writeFileSync(
    join(gen, "handlers.ts"),
    `// GENERATED by olve-build — do not edit.\n` +
      `import type { HandlerRegistry, HarnessInfo } from "@olivervea/pipelines/harness";\n\n` +
      `export const handlers: HandlerRegistry = {\n${registry}\n};\n\n` +
      `export const handlerHashes: Record<string, string> = ${JSON.stringify(hashes, null, 2)};\n\n` +
      `export const harness: HarnessInfo = ${JSON.stringify(harness, null, 2)};\n`,
  );
  const entry = join(gen, "entry.ts");
  writeFileSync(
    entry,
    `// GENERATED by olve-build — do not edit. Entry point of the step binary.\n` +
      `import pipeline from ${JSON.stringify(relPosix(gen, project.pipelineFile))};\n` +
      `import { runHarness } from "@olivervea/pipelines/harness";\n` +
      `import { handlers, handlerHashes, harness } from "./handlers.ts";\n\n` +
      `process.exit(await runHarness({ pipeline, handlers, handlerHashes, harness }, process.argv.slice(2)));\n`,
  );
  return entry;
}

export async function build(dir: string, opts: BuildOptions): Promise<BuildResult> {
  const log = opts.log ?? ((l: string) => process.stderr.write(l + "\n"));
  const stdout = opts.stdout ?? (async (t: string) => void (await Bun.write(Bun.stdout, t)));
  const target = opts.target ?? "bun-linux-x64";
  const project = await loadProject(dir);
  const out = resolve(opts.out);
  mkdirSync(out, { recursive: true });
  const harness = harnessInfo();

  const t0 = performance.now();
  const hashes = await handlerHashes(project, harness);
  const entry = generateEntry(project, Object.fromEntries(Object.entries(hashes).map(([k, v]) => [k, v.handlerHash])), harness);
  log(`olve-build: ${project.handlers.length} handler(s) hashed in ${((performance.now() - t0) / 1000).toFixed(2)}s`);

  // 1. compile
  const binary = join(out, "step");
  rmSync(binary, { force: true });
  const t1 = performance.now();
  const p = Bun.spawnSync([process.execPath, "build", "--compile", `--target=${target}`, ...BUILD_FLAGS, entry, `--outfile=${binary}`], {
    cwd: project.dir,
    stdout: "pipe",
    stderr: "pipe",
    env: { ...process.env, NO_COLOR: "1" },
  });
  if (p.exitCode !== 0 || !existsSync(binary))
    throw new BuildError(`bun build --compile failed (exit ${p.exitCode}):\n${p.stdout.toString()}${p.stderr.toString()}`);
  log(`olve-build: compiled ${target} in ${((performance.now() - t1) / 1000).toFixed(2)}s`);

  // 2. loader check: the harness launches the binary through /olve/lib/<loader>; a musl binary
  //    (e.g. compiled on alpine, where bun-linux-x64 silently yields musl) would not start.
  const expected = target === "bun-linux-x64" ? GLIBC_INTERP : MUSL_INTERP;
  const interp = readInterpreter(binary);
  if (interp !== expected)
    throw new BuildError(`compiled binary has PT_INTERP ${interp ?? "(none)"}, expected ${expected} — compile on a glibc Bun image (oven/bun:<version>-slim), not alpine`);

  // 3. describe (runs the real binary: the manifest is exactly what the step pods will see)
  const d = Bun.spawnSync([binary, "describe"], { cwd: out, stdout: "pipe", stderr: "pipe", env: { PATH: process.env.PATH ?? "/usr/bin:/bin" } });
  if (d.exitCode !== 0) throw new BuildError(`describe failed (exit ${d.exitCode}):\n${d.stderr.toString()}`, d.exitCode ?? 1);
  const manifest = d.stdout.toString();
  const manifestFile = join(out, "manifest.json");
  writeFileSync(manifestFile, manifest);

  // 4. step.tar.zst (deterministic: `step` at the root, 0755, mtime 0)
  const archive = join(out, "step.tar.zst");
  await writeTarZst(archive, [{ path: "step", type: "file", mode: 0o755, source: binary }]);
  writeFileSync(
    join(out, "build.json"),
    canonicalJson({ target, flags: BUILD_FLAGS, harness, handlers: hashes, binarySha256: sha256File(binary), archiveSha256: sha256File(archive) }),
  );
  log(`olve-build: wrote ${archive}`);

  if (opts.uploadUrl) {
    await uploadFile(opts.uploadUrl, archive, log);
    log("olve-build: uploaded step.tar.zst");
  }
  if (opts.sentinels) await stdout(`${MANIFEST_BEGIN}\n${manifest}${MANIFEST_END}\n`);
  return { binary, archive, manifestFile, manifest, hashes, harness };
}
